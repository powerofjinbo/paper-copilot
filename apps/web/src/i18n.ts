export const MESSAGES: Record<Lang, Record<MsgKey, string>> = { en, zh };

export type Vars = Record<string, string | number>;

/** English singulars after a count of exactly 1 ("1 warnings" -> "1 warning"); Chinese has no plural. */
const PLURAL_NOUNS = /(^|[^\d.,])1 (warning|hint|sentence|fact|placeholder|question|blocker|request|text|case|error|item|issue|form|use|ref)s\b/g;

/** Platform key names every string may use: {mod} (⌘ / Ctrl), {alt} (⌥ / Alt), {ghostKey}, {ghostKeyAlt}. */
const KEY_VARS: Vars = { mod: MOD_KEY, alt: ALT_KEY, ghostKey: GHOST_KEY, ghostKeyAlt: GHOST_KEY_ALT };

export function translate(lang: Lang, key: MsgKey, vars?: Vars): string {
  const s = MESSAGES[lang][key] ?? en[key] ?? key;
  const all: Vars = vars ? { ...KEY_VARS, ...vars } : KEY_VARS;
  if (!vars && !s.includes('{')) return s;
  const out = s.replace(/\{(\w+)\}/g, (m, k: string) => (Object.prototype.hasOwnProperty.call(all, k) ? String(all[k]) : m));
  return lang === 'en' ? out.replace(PLURAL_NOUNS, (_m, pre: string, noun: string) => `${pre}1 ${noun}`) : out;
}

export type T = (key: MsgKey, vars?: Vars) => string;

/** Translator bound to the current UI language. */
export function useT(): T {
  const lang = useShell((s) => s.lang);
  return useCallback((key: MsgKey, vars?: Vars) => translate(lang, key, vars), [lang]);
}

